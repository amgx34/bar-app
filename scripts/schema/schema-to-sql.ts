import Papa from 'papaparse';

/**
 * The shape of supabase/diagnostics/export-schema.sql, one array per section.
 * Definitions for constraints, indexes, functions and triggers are exactly what
 * Postgres prints (pg_get_*def), so they are passed through, not re-parsed.
 */
export type SchemaExport = {
  enums: { name: string; labels: string[] }[];
  sequences: { name: string; dataType: string }[];
  tables: { name: string; rls: boolean }[];
  columns: {
    table: string;
    name: string;
    position: number;
    type: string;
    notNull: boolean;
    default: string | null;
    identity: 'always' | 'by default' | null;
    generated: string | null;
  }[];
  constraints: { table: string; name: string; kind: 'p' | 'u' | 'f' | 'c'; definition: string }[];
  indexes: { table: string; name: string; definition: string }[];
  policies: {
    table: string;
    name: string;
    permissive: boolean;
    command: 'ALL' | 'SELECT' | 'INSERT' | 'UPDATE' | 'DELETE';
    roles: string[];
    using: string | null;
    check: string | null;
  }[];
  functions: { name: string; definition: string }[];
  triggers: { table: string; name: string; definition: string }[];
  /** Things that exist but are not recreated: views, domains, composite types. */
  uncovered: { kind: string; name: string }[];
};

const SECTIONS = [
  'enums',
  'sequences',
  'tables',
  'columns',
  'constraints',
  'indexes',
  'policies',
  'functions',
  'triggers',
  'uncovered',
] as const;

export function quoteIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

/**
 * Reads what the SQL editor gave back: CSV with a `section,payload` header, or a
 * JSON array of `{section, payload}` rows. A payload may be a JSON string or
 * already parsed. A section that is absent becomes an empty array.
 */
export function loadExport(raw: string): SchemaExport {
  const text = raw.replace(/^﻿/, '').trim();
  const rows: { section: string; payload: unknown }[] = text.startsWith('[')
    ? JSON.parse(text)
    : Papa.parse<{ section: string; payload: string }>(text, { header: true, skipEmptyLines: true }).data;

  const out: Record<string, unknown[]> = {};
  for (const s of SECTIONS) out[s] = [];
  for (const row of rows) {
    if (!(SECTIONS as readonly string[]).includes(row.section)) continue;
    const payload = typeof row.payload === 'string' ? JSON.parse(row.payload) : row.payload;
    out[row.section] = Array.isArray(payload) ? payload : [];
  }
  return out as unknown as SchemaExport;
}

const q = quoteIdent;
const inPublic = (name: string) => `${q('public')}.${q(name)}`;
const terminated = (sql: string) => {
  const t = sql.trimEnd();
  return t.endsWith(';') ? t : `${t};`;
};
const simpleRole = /^[a-z_][a-z0-9_]*$/;

function columnLine(c: SchemaExport['columns'][number]): string {
  const parts = [q(c.name), c.type];
  if (c.identity) parts.push(c.identity === 'always' ? 'GENERATED ALWAYS AS IDENTITY' : 'GENERATED BY DEFAULT AS IDENTITY');
  else if (c.generated !== null) parts.push(`GENERATED ALWAYS AS (${c.generated}) STORED`);
  else if (c.default !== null) parts.push(`DEFAULT ${c.default}`);
  if (c.notNull) parts.push('NOT NULL');
  return `  ${parts.join(' ')}`;
}

/**
 * True when a function's signature (everything before its body) names one of the
 * tables, meaning it returns or takes that table's row type. Postgres needs the
 * table to exist before such a function can be created. The match is on whole
 * identifiers, so a parameter called `p_staff_id` does not count as `staff`.
 */
function namesTableInSignature(definition: string, tables: string[]): boolean {
  const bodyAt = definition.search(/\sAS\s+\$/i);
  const header = bodyAt === -1 ? definition : definition.slice(0, bodyAt);
  return tables.some((t) => {
    const escaped = t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    return new RegExp(`(?<![\\w"])${escaped}(?![\\w"])`).test(header);
  });
}

/**
 * SQL that recreates the exported `public` schema in an empty project.
 *
 * Order matters and is the point of this function: functions come before tables
 * because a column default can call one; every foreign key comes after every
 * table because two tables may point at each other; policies come last because
 * they refer to tables, columns and functions. A function whose *signature*
 * names a table's row type (`RETURNS accounts`) cannot exist before that table,
 * so those are created right after the tables instead.
 */
export function schemaToSql(s: SchemaExport): string {
  const blocks: string[] = [
    '-- Generated by scripts/schema/schema-to-sql.ts from a read-only schema export.\nset check_function_bodies = off;',
  ];

  for (const e of s.enums) {
    const labels = e.labels.map((l) => `'${l.replace(/'/g, "''")}'`).join(', ');
    blocks.push(`CREATE TYPE ${inPublic(e.name)} AS ENUM (${labels});`);
  }
  for (const seq of s.sequences) blocks.push(`CREATE SEQUENCE ${inPublic(seq.name)} AS ${seq.dataType};`);
  const tableNames = s.tables.map((t) => t.name);
  const needsTables = (f: SchemaExport['functions'][number]) => namesTableInSignature(f.definition, tableNames);
  for (const f of s.functions.filter((f) => !needsTables(f))) blocks.push(terminated(f.definition));

  for (const t of s.tables) {
    const cols = s.columns.filter((c) => c.table === t.name).sort((a, b) => a.position - b.position);
    blocks.push(`CREATE TABLE ${inPublic(t.name)} (\n${cols.map(columnLine).join(',\n')}\n);`);
  }
  for (const f of s.functions.filter(needsTables)) blocks.push(terminated(f.definition));

  const constraint = (k: SchemaExport['constraints'][number]) =>
    `ALTER TABLE ONLY ${inPublic(k.table)} ADD CONSTRAINT ${q(k.name)} ${k.definition};`;
  for (const k of s.constraints.filter((k) => k.kind !== 'f')) blocks.push(constraint(k));
  for (const k of s.constraints.filter((k) => k.kind === 'f')) blocks.push(constraint(k));

  for (const i of s.indexes) blocks.push(terminated(i.definition));
  for (const t of s.triggers) blocks.push(terminated(t.definition));
  for (const t of s.tables.filter((t) => t.rls)) blocks.push(`ALTER TABLE ${inPublic(t.name)} ENABLE ROW LEVEL SECURITY;`);

  for (const p of s.policies) {
    const roles = (p.roles.length ? p.roles : ['public']).map((r) => (simpleRole.test(r) ? r : q(r))).join(', ');
    let sql = `CREATE POLICY ${q(p.name)} ON ${inPublic(p.table)} AS ${p.permissive ? 'PERMISSIVE' : 'RESTRICTIVE'} FOR ${p.command} TO ${roles}`;
    if (p.using !== null) sql += ` USING (${p.using})`;
    if (p.check !== null) sql += ` WITH CHECK (${p.check})`;
    blocks.push(`${sql};`);
  }

  return `${blocks.join('\n\n')}\n`;
}
