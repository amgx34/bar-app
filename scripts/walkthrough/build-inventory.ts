// Usage: node scripts/walkthrough/build-inventory.ts
// Lists every route under app/ and writes docs/superpowers/findings/route-inventory.md,
// a checklist for the screen-by-screen walkthrough. Reads files only.
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { routesFromFiles } from './routes.ts';

const files = (readdirSync('app', { recursive: true }) as string[]).map((f) => `app/${f}`);
const routes = routesFromFiles(files);
const pages = routes.filter((r) => r.kind === 'page');
const apis = routes.filter((r) => r.kind === 'api');

const row = (r: (typeof routes)[number]) =>
  `| \`${r.path}\` | ${r.kind} | ${r.group} | ${r.needsParams ? 'yes' : ''} | |`;
const table = (rs: typeof routes) =>
  ['| path | kind | group | needs params | checked |', '|---|---|---|---|---|', ...rs.map(row)].join('\n');

const md = [
  '# Route inventory',
  '',
  `Generated by \`scripts/walkthrough/build-inventory.ts\`. ${pages.length} pages, ${apis.length} API routes.`,
  'Pages are walked at 1280x800 and 390x844 (Plan 1, Task 9). API routes are listed for completeness and are not walked.',
  '',
  '## Pages',
  '',
  table(pages),
  '',
  '## API routes',
  '',
  table(apis),
  '',
].join('\n');

const out = resolve('docs/superpowers/findings/route-inventory.md');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, md);
console.log(`wrote ${out}: ${pages.length} pages, ${apis.length} api routes`);
console.log(`by group: ${['public', 'auth', 'app', 'staff'].map((g) => `${g} ${pages.filter((p) => p.group === g).length}`).join(' | ')}`);
console.log(`need params: ${pages.filter((p) => p.needsParams).map((p) => p.path).join(', ') || 'none'}`);
